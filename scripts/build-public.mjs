import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const source = path.resolve(root, 'aul sports');
const output = path.resolve(root, 'public');
const marker = path.join(output, '.sports-hub-build');
if (path.dirname(output) !== root) throw new Error('Invalid public output directory.');
if (fs.existsSync(output)) {
  if (fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(marker)) {
    throw new Error('Refusing to replace an unmanaged public directory.');
  }
  fs.rmSync(output, { recursive: true });
}
fs.mkdirSync(output);
fs.writeFileSync(marker, 'Generated by scripts/build-public.mjs\n');
const extensions = new Set(['.pdf', '.html', '.css', '.js', '.json', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.gif', '.ico', '.avif', '.woff', '.woff2', '.ttf', '.mp4', '.webm']);
let count = 0;
function copy(directory, relative = '') {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (['admin.html', 'admin-preview.html'].includes(entry.name.toLowerCase())) continue;
    if (entry.name.startsWith('.') || entry.isSymbolicLink()) continue;
    const next = path.join(relative, entry.name);
    if (entry.isDirectory()) copy(path.join(directory, entry.name), next);
    else if (entry.isFile() && extensions.has(path.extname(entry.name).toLowerCase())) {
      const target = path.join(output, next);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(path.join(source, next), target);
      count++;
    }
  }
}
copy(source);
console.log(`Prepared ${count} frontend files for Vercel's public directory.`);
